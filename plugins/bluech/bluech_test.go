package bluech_test

import (
	"os"
	"path/filepath"
	"runtime"
	"testing"

	"github.com/gavinmcnair/epg/internal/domain"
	"github.com/gavinmcnair/epg/plugins/bluech"
)

func testdataPath(name string) string {
	_, filename, _, _ := runtime.Caller(0)
	return filepath.Join(filepath.Dir(filename), "testdata", name)
}

func TestParseContent(t *testing.T) {
	data, err := os.ReadFile(testdataPath("content.json"))
	if err != nil {
		t.Fatalf("failed to read test data: %v", err)
	}

	channel := domain.Channel{
		SiteID:  "1221",
		XmltvID: "BlueZoom.ch",
		Lang:    "de",
	}

	programs, err := bluech.Parse(data, channel)
	if err != nil {
		t.Fatalf("parse failed: %v", err)
	}

	if len(programs) == 0 {
		t.Fatal("expected at least one program")
	}

	if programs[0].Channel != "BlueZoom.ch" {
		t.Fatalf("expected channel BlueZoom.ch, got %q", programs[0].Channel)
	}

	if programs[0].Source != "tv.blue.ch" {
		t.Fatalf("expected source tv.blue.ch, got %q", programs[0].Source)
	}

	if programs[0].Title == "" {
		t.Fatal("expected non-empty title")
	}
}

func TestParseEmpty(t *testing.T) {
	data, err := os.ReadFile(testdataPath("no_content.json"))
	if err != nil {
		t.Fatalf("failed to read test data: %v", err)
	}

	programs, err := bluech.Parse(data, domain.Channel{})
	if err != nil {
		t.Fatalf("parse failed: %v", err)
	}
	if len(programs) != 0 {
		t.Fatalf("expected 0 programs, got %d", len(programs))
	}
}
