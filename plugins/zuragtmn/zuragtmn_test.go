package zuragtmn_test

import (
	"os"
	"path/filepath"
	"runtime"
	"testing"
	"time"

	"github.com/gavinmcnair/epg/internal/domain"
	"github.com/gavinmcnair/epg/plugins/zuragtmn"
)

func testdataPath(name string) string {
	_, filename, _, _ := runtime.Caller(0)
	return filepath.Join(filepath.Dir(filename), "testdata", name)
}

func TestParseContent(t *testing.T) {
	data, err := os.ReadFile(testdataPath("content.html"))
	if err != nil {
		t.Fatalf("failed to read test data: %v", err)
	}

	date := time.Date(2023, 1, 15, 0, 0, 0, 0, time.UTC)
	channel := domain.Channel{
		ID:      "zuragtmn-mnb",
		XmltvID: "MNB.mn",
		SiteID:  "mnb",
		Lang:    "mn",
	}

	programs, err := zuragtmn.Parse(data, channel, date)
	if err != nil {
		t.Fatalf("parse failed: %v", err)
	}

	if len(programs) == 0 {
		t.Fatal("expected at least one program")
	}

	p := programs[0]

	expectedStart := time.Date(2023, 1, 14, 23, 0, 0, 0, time.UTC)
	if !p.Start.Equal(expectedStart) {
		t.Fatalf("expected start %v, got %v", expectedStart, p.Start)
	}

	expectedStop := time.Date(2023, 1, 15, 0, 0, 0, 0, time.UTC)
	if !p.Stop.Equal(expectedStop) {
		t.Fatalf("expected stop %v, got %v", expectedStop, p.Stop)
	}

	if p.Channel != "MNB.mn" {
		t.Fatalf("expected channel 'MNB.mn', got %q", p.Channel)
	}

	if p.Source != "zuragt.mn" {
		t.Fatalf("expected source 'zuragt.mn', got %q", p.Source)
	}
}

func TestParseEmptyContent(t *testing.T) {
	programs, err := zuragtmn.Parse([]byte(""), domain.Channel{}, time.Now())
	if err != nil {
		t.Fatalf("parse failed: %v", err)
	}
	if len(programs) != 0 {
		t.Fatalf("expected 0 programs, got %d", len(programs))
	}
}

